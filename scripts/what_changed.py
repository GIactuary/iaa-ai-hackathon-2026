"""What changed in a new market (Part 2 kit, decisions/part2_kit_design.md section 2).

Compares every file of a new market's raw folder with the same file of a reference market (Part 1), and the new
market's training rows with its test rows. Writes outputs/what_changed_<name>.md (largest changes first) and a JSON
evidence file. Reports only; every response is a decision for the actuary.
Run: .venv/Scripts/python.exe -I scripts/what_changed.py --new data/raw_part2/emerging --name part2 --codes emerging
     [--ref data/raw_part2/developed]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd

from src import drift, screens
from src.data_rules import CONSTRUCTION_MAP
from src.evidence import write_evidence
from src.thresholds import load_thresholds

ROOT = Path(__file__).resolve().parents[1]
# Documented codes by market. Developed: the Part 1 data page levels plus the variants rule R3 maps. Emerging: the
# local construction codes listed on the Part 2 data page (BRK, STN, WOD, MIX).
DOCUMENTED = {"developed": {"construction_type": set(CONSTRUCTION_MAP)},
              "emerging": {"construction_type": {"brk", "stn", "wod", "mix"}}}


def read_folder(path: Path) -> dict[str, pd.DataFrame]:
    out = {}
    for f in sorted(path.glob("*")):
        if f.suffix == ".parquet":
            out[f.stem] = pd.read_parquet(f)
        elif f.suffix == ".csv":
            out[f.stem] = pd.read_csv(f)
    for df in out.values():
        for c in df.columns:
            if c.endswith("_id"):
                df[c] = df[c].astype("string")
            if c in ("period_start", "period_end", "loss_date", "report_date", "date_of_birth"):
                df[c] = pd.to_datetime(df[c])
    return out


def line_of(stem: str) -> str | None:
    for p in ("policies_", "test_"):
        if stem.startswith(p):
            return stem[len(p):]
    return None


def run(ref_dir: Path, new_dir: Path, name: str, codes: str = "developed") -> dict:
    th = load_thresholds()
    ref, new = read_folder(ref_dir), read_folder(new_dir)
    doc_ref, doc_new = DOCUMENTED["developed"], DOCUMENTED[codes]
    res = dict(files_added=sorted(set(new) - set(ref)), files_removed=sorted(set(ref) - set(new)), files={}, train_test={})
    for stem in sorted(set(ref) & set(new)):
        r, n = ref[stem], new[stem]
        res["files"][stem] = dict(rows_ref=len(r), rows_new=len(n), schema=drift.schema_diff(r, n),
                                  shifts=drift.column_shifts(r, n), detectors=drift.detectors(n, r, doc_new),
                                  detectors_ref=drift.detectors(r, r, doc_ref))
    for stem in sorted(set(new) - set(ref)):
        res["files"][stem] = dict(rows_new=len(new[stem]), detectors=drift.detectors(new[stem], None, doc_new))
    res["market_files"] = drift.market_files(new)
    if "claims" in ref and "claims" in new:
        res["claims"] = dict(ref=drift.claims_summary(ref["claims"], th["screen_z"]), new=drift.claims_summary(new["claims"], th["screen_z"]))
    for stem in new:
        line = line_of(stem)
        if not stem.startswith("policies_") or f"test_{line}" not in new:
            continue
        tr, te = new[stem], new[f"test_{line}"]
        sizes = []
        for measure, seg in screens.SIZE_CHECKS.get(line, []):
            if measure in tr.columns and all(s in tr.columns for s in seg):
                sizes.append(dict(measure=measure, segment=list(seg), referred=int(len(screens.size_referrals(tr, te, measure, seg, th["refer_size_ratio"])))))
        cats = [c for c in tr.columns if c in te.columns and not pd.api.types.is_numeric_dtype(tr[c]) and not c.endswith("_id") and tr[c].nunique() <= 200]
        res["train_test"][line] = dict(rows_train=len(tr), rows_test=len(te), shifts=drift.column_shifts(tr, te), sizes=sizes,
                                       unseen_levels=screens.unseen_levels(tr, te, cats))
    md = report(res, name, ref_dir, new_dir)
    (ROOT / "outputs" / f"what_changed_{name}.md").write_text(md, encoding="utf-8")
    write_evidence({"what_changed": res}, ROOT / "outputs" / f"what_changed_{name}.json")
    return res


def _psi_rows(shifts: dict) -> list[tuple[str, float, dict]]:
    return sorted(((c, s["psi"], s) for c, s in shifts.items() if s.get("psi") is not None), key=lambda t: -t[1])


def report(res: dict, name: str, ref_dir: Path, new_dir: Path) -> str:
    L = [f"# What changed: {name}", "", f"New market `{new_dir}` against reference `{ref_dir}`. Generated by `scripts/what_changed.py`.", ""]
    big, schema, hits, blanks = [], [], [], []
    for stem, f in res["files"].items():
        for c, p, s in _psi_rows(f.get("shifts", {})):
            if p >= 0.1:
                big.append((p, f"{stem}.{c}", s))
        for c, s in f.get("shifts", {}).items():
            if "blank_ref" in s and s["blank_ref"] != s["blank_new"]:
                blanks.append((abs(s["blank_new"] - s["blank_ref"]), f"{stem}.{c}", s["blank_ref"], s["blank_new"]))
        sc = f.get("schema", {})
        if sc and (sc["added"] or sc["removed"] or sc["retyped"]):
            schema.append(f"- **{stem}:** added {sc['added'] or 'none'}; removed {sc['removed'] or 'none'}; retyped {sc['retyped'] or 'none'}")
        d, d0 = f.get("detectors", {}), f.get("detectors_ref", {})
        n_new, n_ref = f.get("rows_new"), f.get("rows_ref")
        for k, val in d.items():
            was = d0.get(k)
            if k.endswith("_lengths") and isinstance(val, dict) and isinstance(was, dict) and set(val) == set(was):
                continue                        # the same identifier lengths as the reference: row counts differ, padding does not
            if val == was:                      # the same as in the reference market: not a change
                continue
            if isinstance(val, int) and val > 0:
                share = f" ({val / n_new:.2%} of rows)" if n_new else ""
                ref_txt = (f" (reference: {was:,}, {was / n_ref:.2%} of rows)" if isinstance(was, int) and n_ref
                           else " (new file)" if was is None else f" (reference: {was})")
                hits.append(f"- **{stem}:** {k.replace('_', ' ')}: {val:,}{share}{ref_txt}")
            elif isinstance(val, (dict, list)) and val:
                ref_txt = f" (reference: {was})" if was is not None else " (new file)"
                hits.append(f"- **{stem}:** {k.replace('_', ' ')}: {val}{ref_txt}")
    blanks.sort(key=lambda t: -t[0])
    big.sort(key=lambda t: -t[0])
    L += ["## In one paragraph", ""]
    L.append(f"{len(big)} columns shifted by a population stability index of 0.1 or more; {len(schema)} files changed shape; "
             f"{len(hits)} trap checks differ from the reference market. Files added: {res['files_added'] or 'none'}; removed: {res['files_removed'] or 'none'}. "
             "Each item below is evidence for the actuary to decide on; nothing has been repaired.")
    L += ["", "## Largest distribution shifts", "",
          "How to read this: the stability index compares the share of rows in each of the reference's ten bands (or each level). "
          "Under 0.1 is usually stable, 0.1 to 0.25 a moderate shift, above 0.25 a large one. Example: an index of 0.30 on sum insured means the new "
          "market's sums insured sit in visibly different bands from the reference's.", ""]
    for p, col, s in big[:25]:
        extra = (f"median {s['q_ref'][3]:,} to {s['q_new'][3]:,}" if s["kind"] == "number" and s.get("q_ref") and s.get("q_new")
                 else f"new levels {s.get('new_levels')}, largest moves {s.get('largest_moves')}")
        L.append(f"- **{col}** PSI {p:.2f}; blank {s['blank_ref']:.1%} to {s['blank_new']:.1%}; {extra}")
    L += ["", "## Largest changes in blank share", "",
          "How to read this: the share of blank values in the reference market, then in the new market, largest change first. "
          "Example: 2.5% to 11.9% means a field blank on one row in forty in Part 1 is blank on about one row in eight here.", ""]
    L += [f"- **{col}** {b0:.1%} to {b1:.1%}" for _, col, b0, b1 in blanks[:25]] or ["None."]
    L += ["", "## Files that changed shape", ""] + (schema or ["None."])
    L += ["", "## Trap checks that differ from the reference", "",
          "How to read this: each line counts rows that look like a Part 1 trap: an exposure equal to the day count was entered in days; "
          "a sum insured ten times the reference's 99th percentile is likely in the wrong unit; several identifier lengths mean padding was lost.", ""] + (hits or ["None."])
    if "claims" in res:
        cr, cn = res["claims"]["ref"], res["claims"]["new"]
        L += ["", "## Claims", "",
              f"- Claims {cr['claims']:,} to {cn['claims']:,}; repudiated {cr['repudiated_share']:.1%} to {cn['repudiated_share']:.1%}; "
              f"nil or negative net cost {cr['nil_or_negative']} to {cn['nil_or_negative']}; negative report lags {cn['negative_lag']}.",
              f"- Report lag in days (median, 90th, 99th percentile): reference {cr['report_lag_days']}; new {cn['report_lag_days']}.",
              f"- Largest claims on the log-cost screen (new): {cn['screen_hits'][:5]}"]
    mf = res.get("market_files", {})
    if mf:
        L += ["", "## Market files beyond the core tables", "",
              "How to read this: the sample submission should hold every test row once and nothing else; every reference policy should be a "
              "test row of the line it names. Example: 'not in test 0, test rows missing 0' means the sample file and the test files agree row for row.", ""]
        if "sample_submission" in mf:
            s = mf["sample_submission"]
            L.append(f"- **sample_submission:** {s['rows']:,} rows against {s['test_rows']:,} test rows; duplicated {s['duplicated']}; "
                     f"not in test {s['not_in_test']}; test rows missing {s['test_rows_missing']}")
        if "reference_policies" in mf:
            r = mf["reference_policies"]
            L.append(f"- **reference_policies:** {r['rows']} rows {r['by_line']}; found in the test files {r['in_test']}; in the test file of their own line {r['in_own_line_test']}")
        if "expenses" in mf:
            L += ["", "| Item | " + " | ".join(k for k in mf["expenses"][0] if k != "item") + " |",
                  "|---|" + "---|" * (len(mf["expenses"][0]) - 1)]
            for e in mf["expenses"]:
                L.append(f"| {e['item']} | " + " | ".join("blank" if v is None else str(v) for k, v in e.items() if k != "item") + " |")
    L += ["", "## Training rows against test rows (new market)", ""]
    for line, t in res["train_test"].items():
        moved = [f"{c} ({p:.2f})" for c, p, _ in _psi_rows(t["shifts"]) if p >= 0.1]
        L.append(f"- **{line}:** {t['rows_train']:,} training and {t['rows_test']:,} test rows; shifted columns {moved or 'none'}; "
                 f"size referrals {[(s['measure'], s['referred']) for s in t['sizes']]}; unseen levels {t['unseen_levels'] or 'none'}")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default=str(ROOT / "data" / "raw"))
    ap.add_argument("--new", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--codes", choices=sorted(DOCUMENTED), default="developed", help="which market's documented codes the new files are checked against")
    a = ap.parse_args()
    run(Path(a.ref), Path(a.new), a.name, a.codes)
    print("written", ROOT / "outputs" / f"what_changed_{a.name}.md")
